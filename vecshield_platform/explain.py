"""Why a detector fired, how sure it is, and what argues against it.

A finding today says *what* was detected. This says whether to believe it.

Three ideas, in the order they matter:

**Counter-signals.** The strongest thing a detector can do for its own
credibility is name the reasons it might be wrong. ``AKIAIOSFODNN7EXAMPLE`` is
shaped exactly like an AWS access key because it *is* the one AWS prints in its
own documentation; ``4111 1111 1111 1111`` passes a Luhn check because the card
networks publish it for testing. A detector that flags these without comment
teaches people to ignore it.

**Confidence is earned, not asserted.** A confidence class is a claim about how
often the detector is right, which is a measurement. Until the benchmark
(v2.2) has measured a detector at a class, that detector emits ``uncertain``
and says why. :data:`CALIBRATED` is deliberately empty: nothing has been
measured yet, so nothing may claim more.

**Redaction by default.** An explanation carries the matched span's position
and a masked preview, never the raw secret. The point is to let a reader judge
the match, not to copy it into a browser, a log, and a screenshot.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from dataclasses import dataclass, field
from typing import Any, Optional

#: Ordered from most to least certain. `uncertain` is the floor, not an error.
CONFIDENCE_CLASSES = ("likely", "possible", "uncertain")

#: Where the benchmark writes what each detector has earned. The file is
#: generated by `vecshield-platform benchmark calibrate`; it is not written
#: by hand, because a hand-written entry is a confidence claim with no
#: measurement behind it.
CALIBRATION_PATH = Path(__file__).resolve().parent.parent / "benchmark" / "calibration.json"


def _load_calibration(path: Path = CALIBRATION_PATH) -> dict[str, set[str]]:
    """Read the earned classes, or none at all.

    A missing or unreadable file means nothing has been measured here, which
    is the safe reading: every detector falls back to `uncertain`.
    """
    try:
        document = json.loads(path.read_text())
    except (OSError, ValueError):
        return {}
    earned: dict[str, set[str]] = {}
    for detector, record in (document.get("detectors") or {}).items():
        claim = record.get("class")
        if claim and claim != "uncertain":
            # A detector that earned `likely` may also report `possible`; the
            # reverse is not true.
            index = CONFIDENCE_CLASSES.index(claim)
            earned[detector] = set(CONFIDENCE_CLASSES[index:-1])
    return earned


#: Detector -> the confidence classes the benchmark has measured it at.
CALIBRATED: dict[str, set[str]] = _load_calibration()

#: Values published by vendors as examples or test data. Matching one of these
#: is strong evidence the finding is not a live credential.
_PUBLISHED_EXAMPLES = {
    # AWS documentation credentials, printed in AWS's own guides.
    "akiaiosfodnn7example": "AWS publishes this access key id in its documentation",
    "wjalrxutnfemi/k7mdeng/bpxrficyexamplekey": "AWS publishes this secret key in its documentation",
    # Card numbers the networks publish for testing. They pass a Luhn check by
    # design, which is exactly why a checksum alone cannot clear them.
    "4111111111111111": "Visa publishes this as a test card number",
    "4242424242424242": "Widely published test card number",
    "5555555555554444": "Mastercard publishes this as a test card number",
    "5105105105105100": "Mastercard publishes this as a test card number",
    "378282246310005": "American Express publishes this as a test card number",
    "371449635398431": "American Express publishes this as a test card number",
    "6011111111111117": "Discover publishes this as a test card number",
    "3530111333300000": "JCB publishes this as a test card number",
    "000000000": "Placeholder digits, not an identifier",
    "123456789": "Sequential placeholder digits",
    "123-45-6789": "The US Social Security Administration's published example number",
}

#: Key prefixes vendors reserve for test mode.
_TEST_KEY_PREFIXES = {
    "sk_test_": "Stripe reserves the sk_test_ prefix for test-mode keys",
    "pk_test_": "Stripe reserves the pk_test_ prefix for test-mode keys",
    "whsec_test_": "Stripe reserves this prefix for test-mode webhook secrets",
}

#: Collection or metadata naming that says the content is not production data.
_FIXTURE_WORDS = ("fixture", "fixtures", "sample", "samples", "example", "examples",
                  "test", "tests", "demo", "seed", "mock", "dummy", "sandbox")

#: Tokens that stand in for a value in a configuration template. A template is
#: not a leak, and a detector that cannot tell them apart teaches people to
#: ignore it.
_PLACEHOLDER_TOKENS = ("password", "passwd", "secret", "token", "apikey", "api_key",
                       "username", "user", "host", "hostname", "dbname", "database",
                       "changeme", "xxxx", "yyyy", "your_", "example", "placeholder",
                       "redacted", "elided")

#: Reserved names that cannot route anywhere real (RFC 2606, RFC 6761).
_RESERVED_DOMAINS = ("example.com", "example.org", "example.net", ".example",
                     ".test", ".invalid", ".localhost")


@dataclass(frozen=True)
class CounterSignal:
    """One reason this match may not be what it looks like."""

    code: str
    detail: str

    def to_dict(self) -> dict[str, str]:
        return {"code": self.code, "detail": self.detail}


@dataclass(frozen=True)
class Explanation:
    """Why a detector fired on a span, and how far to trust it."""

    detector: str
    label: str
    matched_preview: str
    start: Optional[int] = None
    end: Optional[int] = None
    confidence: str = "uncertain"
    confidence_reason: str = ""
    counter_signals: list[CounterSignal] = field(default_factory=list)

    @property
    def disputed(self) -> bool:
        return bool(self.counter_signals)

    def to_dict(self) -> dict[str, Any]:
        return {
            "detector": self.detector,
            "label": self.label,
            "matched_preview": self.matched_preview,
            "start": self.start, "end": self.end,
            "confidence": self.confidence,
            "confidence_reason": self.confidence_reason,
            "counter_signals": [c.to_dict() for c in self.counter_signals],
            "disputed": self.disputed,
        }


def confidence_for(detector: str, proposed: str = "likely") -> tuple[str, str]:
    """The class a detector is allowed to claim, and why.

    A detector may only emit a class the benchmark has measured it at. Until
    then it says `uncertain` and names the reason, rather than borrowing
    authority it has not earned.
    """
    if proposed not in CONFIDENCE_CLASSES:
        raise ValueError(f"unknown confidence class: {proposed}")
    measured = CALIBRATED.get(detector, set())
    # The strongest class the detector holds, at or below what was proposed.
    # An earlier version returned 'uncertain' whenever the exact proposed
    # class was not held — so a detector measured at 'possible' was reported
    # as 'uncertain' with a message saying it had no measured precision, which
    # was false, on every finding it appeared in.
    for candidate in CONFIDENCE_CLASSES[CONFIDENCE_CLASSES.index(proposed):-1]:
        if candidate in measured:
            if candidate == proposed:
                return candidate, (f"Measured precision for {detector} at "
                                   f"'{candidate}' on the benchmark.")
            return candidate, (f"Measured precision for {detector} supports "
                               f"'{candidate}', not '{proposed}': the interval's "
                               "lower bound does not clear the higher floor.")
    return "uncertain", (
        f"No measured precision for {detector}. Confidence is reported as "
        "'uncertain' until the benchmark establishes one.")


def _mask(value: str) -> str:
    """Keep the shape, drop the secret."""
    text = str(value)
    if len(text) <= 6:
        return text[0] + "•" * (len(text) - 1) if text else ""
    return f"{text[:2]}{'•' * (len(text) - 4)}{text[-2:]}"


def _normalize(value: str) -> str:
    return re.sub(r"[\s-]", "", str(value)).lower()


def counter_signals(matched: str, *, text: str = "", collection: str = "",
                    metadata: Optional[dict[str, Any]] = None,
                    label: str = "") -> list[CounterSignal]:
    """Reasons this match may not be what it looks like.

    Every signal here is checkable and specific. None of them *clear* a
    finding — that is a person's decision — they say what a reviewer would
    otherwise have to work out for themselves.
    """
    signals: list[CounterSignal] = []
    raw = str(matched or "")
    normalized = _normalize(raw)
    lowered = raw.lower()

    published = _PUBLISHED_EXAMPLES.get(normalized) or _PUBLISHED_EXAMPLES.get(lowered)
    if published:
        signals.append(CounterSignal("published_example", published))

    for prefix, detail in _TEST_KEY_PREFIXES.items():
        if lowered.startswith(prefix):
            signals.append(CounterSignal("vendor_test_prefix", detail))
            break

    if any(domain in lowered for domain in _RESERVED_DOMAINS):
        signals.append(CounterSignal(
            "reserved_domain",
            "Uses a domain reserved for documentation and testing (RFC 2606/6761)"))

    haystack = " ".join([collection or "", " ".join(
        f"{k} {v}" for k, v in (metadata or {}).items())]).lower()
    # Split on anything that is not a letter or digit, so `test_fixtures` and
    # `qa-sandbox` tokenize the way a reader reads them — and `contest` stays
    # one word rather than containing `test`.
    tokens = set(re.split(r"[^a-z0-9]+", haystack)) - {""}
    hit = next((word for word in _FIXTURE_WORDS if word in tokens), None)
    if hit:
        signals.append(CounterSignal(
            "non_production_scope",
            f"Its collection or metadata is labelled '{hit}', which suggests "
            "content that is not production data"))

    # A value made of placeholder words is a template, not a credential.
    words = set(re.split(r"[^a-z0-9_]+", lowered)) - {""}
    if raw and (any(w in _PLACEHOLDER_TOKENS for w in words)
                or any(token in lowered for token in ("changeme", "your_", "<", ">"))):
        signals.append(CounterSignal(
            "placeholder_token",
            "Contains placeholder words rather than a value, which is how a "
            "configuration template is written"))

    if raw and text:
        # A value inside a code fence or quotes is often documentation about the
        # thing rather than the thing itself — how a guide about prompt
        # injection comes to look like an injection.
        at = text.find(raw)
        if at > 0:
            before = text[max(0, at - 3):at]
            after = text[at + len(raw):at + len(raw) + 3]
            if ("`" in before and "`" in after) or ('"' in before and '"' in after):
                signals.append(CounterSignal(
                    "quoted_in_text",
                    "The value appears quoted or fenced, which often marks an "
                    "example rather than a live value"))

    return signals


def explain_span(span: dict[str, Any], *, text: str = "", collection: str = "",
                 metadata: Optional[dict[str, Any]] = None,
                 matched: str = "") -> Explanation:
    """Build an explanation from a classifier span.

    The span already carries the detector, the offsets, and a masked preview;
    this adds the part a reader needs and the classifier does not provide.
    """
    detector = str(span.get("detector", "unknown"))
    label = str(span.get("label", ""))
    preview = str(span.get("preview") or (_mask(matched) if matched else ""))
    confidence, reason = confidence_for(detector)
    return Explanation(
        detector=detector, label=label, matched_preview=preview,
        start=span.get("start"), end=span.get("end"),
        confidence=confidence, confidence_reason=reason,
        counter_signals=counter_signals(matched, text=text, collection=collection,
                                        metadata=metadata, label=label))


def matched_text(span: dict[str, Any], surfaces: dict[str, str]) -> str:
    """The exact text a span covers.

    Offsets are relative to the *surface* the span was found in — a chunk's
    text, or one metadata field — and each span names its surface. Slicing a
    concatenation of all surfaces would return the wrong characters, and the
    counter-signals drawn from them would be wrong too.
    """
    if not isinstance(span, dict):
        return ""
    surface = span.get("surface")
    start, end = span.get("start"), span.get("end")
    if not isinstance(start, int) or not isinstance(end, int):
        return ""
    # A negative offset is nonsense from a classifier, and Python would happily
    # slice from the end and hand back a plausible-looking substring — which
    # every counter-signal would then be computed against.
    if start < 0 or end < start:
        return ""
    if surface is not None:
        return str(surfaces.get(str(surface), ""))[start:end]
    # A span with no surface predates surface-aware classification; the chunk
    # text is the only defensible guess, and only when there is one surface.
    if len(surfaces) == 1:
        return next(iter(surfaces.values()))[start:end]
    return str(surfaces.get("text", ""))[start:end]


def explain_example(example: dict[str, Any], *, collection: str = "",
                    surfaces: Optional[dict[str, str]] = None,
                    metadata: Optional[dict[str, Any]] = None
                    ) -> list[dict[str, Any]]:
    """Explanations for every span in one captured example chunk."""
    surfaces = surfaces or {}
    out = []
    # A corpus run feeds thousands of items through here; one malformed span
    # must not end the run.
    for span in (example or {}).get("spans") or []:
        if not isinstance(span, dict):
            continue
        matched = matched_text(span, surfaces)
        surface_text = str(surfaces.get(str(span.get("surface", "text")), ""))
        out.append(explain_span(span, text=surface_text, collection=collection,
                                metadata=metadata, matched=matched).to_dict())
    return out


def summarize_causes(findings: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Group findings by the signal that produced them.

    "47 findings" is a list to work through; "3 causes across 47 locations" is
    a decision to make three times.
    """
    causes: dict[str, dict[str, Any]] = {}
    for finding in findings or []:
        if not isinstance(finding, dict):
            continue
        explanations = ((finding.get("evidence") or {}).get("explanations")) or []
        explanations = [e for e in explanations if isinstance(e, dict)]
        keys = {e.get("detector", "unknown") for e in explanations} or {
            str((finding.get("evidence") or {}).get("check")
                or finding.get("category") or "unattributed")}
        for key in keys:
            cause = causes.setdefault(key, {
                "cause": key, "findings": 0, "locations": set(),
                "disputed": 0, "severities": {},
            })
            cause["findings"] += 1
            if finding.get("collection"):
                cause["locations"].add(finding["collection"])
            severity = str(finding.get("severity", "info"))
            cause["severities"][severity] = cause["severities"].get(severity, 0) + 1
            if any(e.get("disputed") for e in explanations if
                   e.get("detector", "unknown") == key):
                cause["disputed"] += 1
    return sorted(
        ({**c, "locations": sorted(c["locations"])} for c in causes.values()),
        key=lambda c: (-c["findings"], c["cause"]))
